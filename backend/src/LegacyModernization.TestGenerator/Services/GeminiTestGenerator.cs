using Mscc.GenerativeAI;
using LegacyModernization.Analyzer.Models;
using LegacyModernization.TestGenerator.Models;
using Microsoft.Extensions.Configuration;

namespace LegacyModernization.TestGenerator.Services;

public class GeminiTestGenerator : ITestGenerator
{
    private readonly GenerativeModel _model;

    public GeminiTestGenerator()
    {
        var config = new ConfigurationBuilder()
            .SetBasePath(AppContext.BaseDirectory)
            .AddJsonFile("appsettings.json", optional: false)
            .Build();

        var apiKey = config["Gemini:ApiKey"];

        if (string.IsNullOrWhiteSpace(apiKey))
        {
            throw new InvalidOperationException(
                "Gemini API key was not found in appsettings.json.");
        }

        var googleAI = new GoogleAI(apiKey);

        _model = googleAI.GenerativeModel("gemini-2.5-flash");
    }

    public async Task<GeneratedTest> GenerateTestAsync(AnalysisIssue issue)
    {
        var prompt = $"""
You are a senior .NET testing engineer.

Generate an xUnit test for the following legacy C# issue.

Rule:
{issue.RuleId}

Title:
{issue.Title}

Description:
{issue.Description}

File:
{issue.FilePath}

Code:
{issue.CodeSnippet}

Requirements:

1. Use xUnit.
2. Test the CURRENT behavior of the legacy code.
3. Do not modify the production code.
4. Return ONLY compilable C# code.
5. Include all necessary using statements.
6. Create a meaningful test class and test method.
7. Do not use Markdown code fences.
8. The test must contain at least one [Fact] or [Theory].
""";

        var response = await _model.GenerateContent(prompt);

        return new GeneratedTest
        {
            TestClassName = $"{issue.RuleId}GeneratedTests",
            TestCode = response.Text ?? "",
            TargetFile = issue.FilePath,
            Explanation = "Generated by Gemini"
        };
    }
}